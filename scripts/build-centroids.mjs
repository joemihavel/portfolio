// One-off: work out where to put a country's dot on the map.
//
// Derived from the same Natural Earth data as the land outline rather than
// hand-typed, so the dots actually sit on their countries. Run with
// `node scripts/build-centroids.mjs`; the output is committed.

import { writeFile } from "node:fs/promises";
import { feature } from "topojson-client";
import isoCountries from "i18n-iso-countries";

const SRC = "https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json";
const OUT = "src/data/meanwhile/centroids.ts";

// Every country Natural Earth knows about gets a dot, not just the ones in the
// composer's picker — a visitor can arrive from anywhere, and a country with no
// position would silently vanish from the map. The features carry only a
// numeric ISO code, so it is converted to the alpha-2 the tally uses.

const geo = feature(await (await fetch(SRC)).json(), "countries");

const out = {};
let missed = [];

for (const f of geo.features) {
  const code = isoCountries.numericToAlpha2(String(f.id ?? "").padStart(3, "0"));
  if (!code) {
    missed.push(f.properties?.name);
    continue;
  }

  // The ring with the most points stands in for the mainland. Averaging every
  // ring would drag the United States into the Pacific via Hawaii, and Norway
  // into the Arctic via Svalbard.
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  let best = [];
  for (const poly of polys) if (poly[0] && poly[0].length > best.length) best = poly[0];
  if (!best.length) continue;

  let lng = 0;
  let lat = 0;
  for (const [x, y] of best) { lng += x; lat += y; }
  out[code] = [
    Math.round((lat / best.length) * 100) / 100,
    Math.round((lng / best.length) * 100) / 100,
  ];
}

await writeFile(
  OUT,
  `// GENERATED by scripts/build-centroids.mjs — do not edit by hand.\n` +
    `// [latitude, longitude] of each country's largest landmass.\n` +
    `export const CENTROIDS: Record<string, [number, number]> = ${JSON.stringify(out, null, 0)};\n`
);

console.log(`mapped ${Object.keys(out).length} of ${geo.features.length} countries`);
if (missed.length) console.log(`unmatched Natural Earth names: ${missed.length}`);
