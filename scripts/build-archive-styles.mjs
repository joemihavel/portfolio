// The archive frames use the original Figma utility values. Compile only their
// classes and scope every selector so the portfolio's typography is unaffected.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {compile}=require('@tailwindcss/node');
const postcss=require('postcss');
const root=path.resolve(import.meta.dirname,'..');
const dir=path.join(root,'src/components/archive');
const candidates=new Set();
for(const file of await fs.readdir(dir)){
 if(!file.endsWith('.astro'))continue;
 const content=await fs.readFile(path.join(dir,file),'utf8');
 for(const match of content.matchAll(/class="([^"]+)"/g))for(const name of match[1].split(/\s+/))candidates.add(name);
}
const sequences=JSON.parse(await fs.readFile(path.join(root,'src/data/archive-motion.json'),'utf8'));
for(const sequence of sequences)for(const state of sequence.states){
 for(const match of state.html.matchAll(/class="([^"]+)"/g))for(const name of match[1].replaceAll('&quot;','"').split(/\s+/))candidates.add(name);
}
const compiler=await compile('@import "tailwindcss/theme" layer(theme); @import "tailwindcss/utilities" layer(utilities);',{base:root,onDependency(){}});
const sheet=postcss.parse(compiler.build([...candidates]));
sheet.walkRules(rule=>{
 if(rule.parent?.type==='rule')return;
 let parent=rule.parent;
 while(parent){if(parent.type==='atrule'&&/keyframes$/.test(parent.name))return;parent=parent.parent;}
 rule.selectors=[...new Set(rule.selectors.map(s=>s===':root'||s===':host'?'.archive-stage':`:where(.archive-stage) ${s}`))];
});
sheet.walkAtRules('layer',rule=>{if(rule.nodes)rule.replaceWith(...rule.nodes);else rule.remove();});
sheet.walkComments(comment=>comment.remove());
await fs.writeFile(path.join(root,'src/styles/archive-native.css'),'/* Generated by scripts/build-archive-styles.mjs. */\n'+sheet.toString());
console.log(`Scoped ${candidates.size} archive utility values.`);
